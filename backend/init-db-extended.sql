-- ============================================
-- 🧠 Neural-Care Mode (Continuous AI Health Guardian)
-- ============================================

-- Health Context Memory - Stores AI's understanding of patient health patterns
CREATE TABLE IF NOT EXISTS health_context_memory (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id UUID NOT NULL REFERENCES patient_profiles(id) ON DELETE CASCADE,
  context_type VARCHAR(50) NOT NULL, -- 'symptom_pattern', 'vital_trend', 'sleep_pattern', 'stress_pattern', 'lab_trend'
  context_data JSONB NOT NULL, -- Pattern data, trends, correlations
  confidence_score DOUBLE PRECISION DEFAULT 0.0,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Health Alerts - Proactive alerts generated by AI
CREATE TABLE IF NOT EXISTS health_alerts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id UUID NOT NULL REFERENCES patient_profiles(id) ON DELETE CASCADE,
  alert_type VARCHAR(50) NOT NULL, -- 'pattern_detected', 'risk_high', 'anomaly_detected'
  severity VARCHAR(20) NOT NULL, -- 'low', 'medium', 'high', 'critical'
  title VARCHAR(200) NOT NULL,
  message TEXT NOT NULL,
  context_data JSONB, -- Supporting data (symptoms, vitals, etc.)
  acknowledged BOOLEAN DEFAULT FALSE,
  acknowledged_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_health_context_memory_patient_id ON health_context_memory(patient_id);
CREATE INDEX IF NOT EXISTS idx_health_context_memory_type ON health_context_memory(context_type);
CREATE INDEX IF NOT EXISTS idx_health_alerts_patient_id ON health_alerts(patient_id);
CREATE INDEX IF NOT EXISTS idx_health_alerts_severity ON health_alerts(severity);
CREATE INDEX IF NOT EXISTS idx_health_alerts_acknowledged ON health_alerts(acknowledged);
CREATE INDEX IF NOT EXISTS idx_health_alerts_created_at ON health_alerts(created_at DESC);

-- ============================================
-- 📍 Live Doctor Map + Walk-in Queue
-- ============================================

-- Doctors Registry (extends hospital registry)
CREATE TABLE IF NOT EXISTS doctors (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES users(id) ON DELETE SET NULL,
  name VARCHAR(200) NOT NULL,
  specialty VARCHAR(100),
  qualification TEXT,
  license_number VARCHAR(100),
  hospital_id UUID,
  clinic_name VARCHAR(200),
  location_lat DOUBLE PRECISION,
  location_lng DOUBLE PRECISION,
  address TEXT,
  phone VARCHAR(20),
  email VARCHAR(255),
  is_available BOOLEAN DEFAULT TRUE,
  available_slots JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Walk-in Queue Management
CREATE TABLE IF NOT EXISTS walk_in_queue (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  doctor_id UUID NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
  patient_id UUID NOT NULL REFERENCES patient_profiles(id) ON DELETE CASCADE,
  queue_number INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'waiting', -- 'waiting', 'in_progress', 'completed', 'cancelled'
  estimated_wait_time INTEGER, -- minutes
  checked_in_at TIMESTAMP NOT NULL DEFAULT NOW(),
  called_at TIMESTAMP,
  completed_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_doctors_location ON doctors USING GIST (point(location_lng, location_lat));
CREATE INDEX IF NOT EXISTS idx_doctors_specialty ON doctors(specialty);
CREATE INDEX IF NOT EXISTS idx_doctors_available ON doctors(is_available);
CREATE INDEX IF NOT EXISTS idx_walk_in_queue_doctor_id ON walk_in_queue(doctor_id);
CREATE INDEX IF NOT EXISTS idx_walk_in_queue_status ON walk_in_queue(status);
CREATE INDEX IF NOT EXISTS idx_walk_in_queue_checked_in ON walk_in_queue(checked_in_at);

-- ============================================
-- 🎥 AI Medical Camera + 3D Body Scan
-- ============================================

-- 3D Body Scan Records
CREATE TABLE IF NOT EXISTS body_scans (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id UUID NOT NULL REFERENCES patient_profiles(id) ON DELETE CASCADE,
  scan_type VARCHAR(50) NOT NULL, -- 'full_body', 'posture', 'wound', 'skin_lesion'
  mesh_data_url TEXT, -- URL to 3D mesh file
  reference_points JSONB, -- Key measurement points
  measurements JSONB, -- Dimensions, angles, etc.
  comparison_data JSONB, -- Changes from previous scans
  ai_analysis JSONB, -- AI-generated insights
  created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Skin Lesion Tracking
CREATE TABLE IF NOT EXISTS skin_lesions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id UUID NOT NULL REFERENCES patient_profiles(id) ON DELETE CASCADE,
  lesion_id VARCHAR(100) NOT NULL, -- Unique identifier for this specific lesion
  body_part VARCHAR(100),
  position_data JSONB, -- Location on body
  image_urls TEXT[], -- Array of image URLs over time
  measurements JSONB, -- Size, shape, color metrics
  change_percentage DOUBLE PRECISION, -- Change from baseline
  risk_assessment JSONB,
  monitoring_status VARCHAR(20) DEFAULT 'active', -- 'active', 'resolved', 'monitoring'
  baseline_scan_id UUID REFERENCES body_scans(id),
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_body_scans_patient_id ON body_scans(patient_id);
CREATE INDEX IF NOT EXISTS idx_body_scans_type ON body_scans(scan_type);
CREATE INDEX IF NOT EXISTS idx_skin_lesions_patient_id ON skin_lesions(patient_id);
CREATE INDEX IF NOT EXISTS idx_skin_lesions_lesion_id ON skin_lesions(lesion_id);
CREATE INDEX IF NOT EXISTS idx_skin_lesions_status ON skin_lesions(monitoring_status);

